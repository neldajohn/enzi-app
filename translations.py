def translate(key, lang, **kwargs):
    lang_dict = TRANSLATIONS.get(lang) or TRANSLATIONS["en"]
    text = lang_dict.get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
